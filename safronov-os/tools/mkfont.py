#!/usr/bin/env python3
"""Convert PSF console fonts into a C header for the Safronov OS kernel.

Usage: mkfont.py small.psf.gz big.psf.gz > src/font.h

Only the code points Safronov OS actually needs are kept (ASCII, Latin-1,
Cyrillic, box drawing, blocks, a few symbols) to keep the kernel small.
"""
import gzip
import struct
import sys

WANTED = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x400, 0x460))
    + list(range(0x2500, 0x25A0))
    + [0x2022, 0x2026, 0x2116, 0x2190, 0x2191, 0x2192, 0x2193, 0x2665, 0x263A]
)


def load_psf(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":  # PSF1
        mode, h = data[2], data[3]
        n = 512 if mode & 1 else 256
        w, bpg, off = 8, h, 4
        glyphs = [data[off + i * bpg: off + (i + 1) * bpg] for i in range(n)]
        table = {}
        if mode & 2:
            p = off + n * bpg
            for i in range(n):
                while True:
                    (u,) = struct.unpack_from("<H", data, p)
                    p += 2
                    if u == 0xFFFF:
                        break
                    if u == 0xFFFE:
                        continue
                    table.setdefault(u, i)
        return w, h, glyphs, table
    magic, ver, hsz, flags, n, bpg, h, w = struct.unpack_from("<8I", data)
    assert magic == 0x864AB572, "not a PSF font"
    glyphs = [data[hsz + i * bpg: hsz + (i + 1) * bpg] for i in range(n)]
    table = {}
    if flags & 1:
        p = hsz + n * bpg
        for i in range(n):
            while data[p] != 0xFF:
                if data[p] == 0xFE:  # sequences are skipped
                    while data[p] != 0xFF:
                        p += 1
                    break
                b = data[p]
                ln = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
                table.setdefault(ord(data[p:p + ln].decode("utf-8")), i)
                p += ln
            p += 1
    return w, h, glyphs, table


def main():
    small = load_psf(sys.argv[1])
    big = load_psf(sys.argv[2])
    cps = sorted(set(c for c in WANTED if c in small[3] and c in big[3]))
    out = ["/* Generated by tools/mkfont.py from Terminus (SIL OFL 1.1). Do not edit. */",
           "#pragma once", "#include <stdint.h>", ""]
    out.append(f"#define FONT_GLYPHS {len(cps)}")
    for name, (w, h, glyphs, table) in (("small", small), ("big", big)):
        out.append(f"#define FONT_{name.upper()}_W {w}")
        out.append(f"#define FONT_{name.upper()}_H {h}")
        bpg = ((w + 7) // 8) * h
        out.append(f"static const uint8_t font_{name}[FONT_GLYPHS][{bpg}] = {{")
        for c in cps:
            g = glyphs[table[c]][:bpg]
            out.append("  {" + ",".join(str(b) for b in g) + "},")
        out.append("};")
    out.append("static const uint16_t font_codepoints[FONT_GLYPHS] = {")
    for i in range(0, len(cps), 16):
        out.append("  " + ",".join(hex(c) for c in cps[i:i + 16]) + ",")
    out.append("};")
    print("\n".join(out))
    missing = [hex(c) for c in WANTED if c not in cps]
    if missing:
        print(f"note: {len(missing)} code points missing: {' '.join(missing[:20])}", file=sys.stderr)


if __name__ == "__main__":
    main()
